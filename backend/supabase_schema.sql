-- Run this entire script once in Supabase > SQL Editor.
-- The backend uses the Supabase secret/service-role key on the server only.
-- Never put that key in frontend HTML or JavaScript.

create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text not null unique,
  password_hash text not null,
  phone text default '',
  city text default '',
  business_name text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  seller_id uuid not null references public.users(id) on delete cascade,
  name text not null,
  category text not null,
  keywords text default '',
  price numeric,
  min_qty integer,
  unit text default 'pc',
  moq integer default 1,
  supplier text default '',
  city text default '',
  tag text default '',
  description text default '',
  created_at timestamptz not null default now()
);

create index if not exists products_category_idx on public.products(category);
create index if not exists products_seller_idx on public.products(seller_id);

create table if not exists public.custom_categories (
  id text primary key,
  name text not null unique,
  hue integer default 200
);

create table if not exists public.requirements (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  firm_name text not null,
  product_name text not null,
  quantity numeric not null,
  unit text default 'pc',
  city text default '',
  phone text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  seller_id uuid not null references public.users(id) on delete cascade,
  quantity numeric not null,
  unit text default 'pc',
  buyer_name text default '',
  phone text not null,
  created_at timestamptz not null default now()
);

create index if not exists enquiries_seller_idx on public.enquiries(seller_id, id desc);

create table if not exists public.requests (
  id bigint generated by default as identity primary key,
  buyer_id uuid not null references public.users(id) on delete cascade,
  title text not null,
  category text not null,
  quantity numeric,
  city text default '',
  budget numeric,
  details text default '',
  status text default 'open',
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  request_id bigint not null references public.requests(id) on delete cascade,
  is_read boolean not null default false,
  created_at timestamptz not null default now(),
  unique(user_id, request_id)
);

create table if not exists public.quotes (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.requests(id) on delete cascade,
  seller_id uuid not null references public.users(id) on delete cascade,
  price numeric not null,
  message text default '',
  created_at timestamptz not null default now(),
  unique(request_id, seller_id)
);

-- RLS is enabled. The backend's secret/service-role key bypasses RLS.
-- Do not use the secret/service-role key in browser code.
alter table public.users enable row level security;
alter table public.products enable row level security;
alter table public.custom_categories enable row level security;
alter table public.requirements enable row level security;
alter table public.enquiries enable row level security;
alter table public.requests enable row level security;
alter table public.notifications enable row level security;
alter table public.quotes enable row level security;
